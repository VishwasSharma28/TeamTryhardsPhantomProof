"""
=============================================================================
payment_validator.py — UPI Receipt Field Extraction & Heuristic Rule Engine
=============================================================================
ROLE IN THE ARCHITECTURE:
  This module parses raw OCR text extracted from payment receipts (Paytm, GPay,
  PhonePe) and performs structural validation on financial entities:
    1. Regex entity extraction (Amount, UTR, Bank name from UPI VPA handle).
    2. Indian UPI 12-digit UTR format validation.
    3. Anomaly detection (repeated digits like '111111111111', sequential runs,
       suspicious edge amounts like 499 or 1001).

TECHNOLOGY:
  Pure Python regular expressions (`re`) and deterministic business logic.
=============================================================================
"""

import re


def extract_fields(text: str) -> dict:
    """
    Extracts key payment attributes from OCR text using specialized Regex patterns.

    Parameters:
        text (str): Full text extracted by EasyOCR from the receipt screenshot.

    Returns:
        dict: {'amount': str, 'utr': str, 'bank': str}
    """
    amount = ""
    # Note: OCR often misreads the Indian Rupee symbol '₹' as the digit '2' or letter 'Z'
    AMOUNT_PATTERN = r'[₹2Z]\s?(\d+(?:,\d{3})*(?:\.\d{2})?)'
    match = re.search(AMOUNT_PATTERN, text, re.IGNORECASE)
    
    if match:
        amount = '₹' + match.group(1).replace(',', '').strip()

    # Search for a 12-character alphanumeric transaction reference (UTR)
    utr_match = re.search(r"\b[A-Z0-9]{12}\b", text)
    utr = utr_match.group(0).strip() if utr_match else ""

    bank = ""
    # Extract the banking PSP handle after '@' in UPI VPA (e.g. merchant@okaxis -> AXIS)
    upi_match = re.search(r'[a-zA-Z0-9.\-_]+@([a-zA-Z]+)', text)
    if upi_match:
        bank_candidate = upi_match.group(1).upper()
        if len(bank_candidate) > 2:
            bank = bank_candidate
            # Standardize common UPI provider prefixes
            if bank.startswith("OK"):
                bank = bank[2:]  # Google Pay handles: okaxis -> axis, oksbi -> sbi
            elif bank.startswith("YBL"):
                bank = "YESBANK" # PhonePe handles: ybl -> YESBANK
            elif bank.startswith("IBL"):
                bank = "ICICI"
    
    if not bank or len(bank) <= 2:
        # Fallback keyword lookup if UPI VPA handle is missing
        BANKS = ["HDFC", "SBI", "ICICI", "Axis", "Kotak", "Paytm", "PhonePe", "Google Pay"]
        text_lower = text.lower()
        for b in BANKS:
            if b.lower() in text_lower:
                bank = b
                break
                
    return {
        "amount": amount,
        "utr": utr,
        "bank": bank
    }


def validate_utr(utr: str) -> bool:
    """
    Validates whether the UTR adheres to the 12-digit Indian UPI specification.
    Fake payment generator apps often invent 8-10 digit numbers or insert random characters.
    """
    if not utr or len(utr) != 12:
        return False
        
    # Standard UPI UTRs in India are exactly 12 digits.
    if not utr.isdigit():
        return False
        
    return True


def is_utr_numeric_only(utr: str) -> bool:
    """
    Checks if UTR contains only digits. While UPI UTRs are numeric, certain bank
    references include alphabetic prefixes.
    """
    return utr.isdigit()


def is_amount_suspiciously_round(amount_str: str) -> bool:
    """
    Identifies edge-case payment amounts often used in phishing or mock tests
    (e.g., test transactions of 499, 999, 1001).
    """
    if not amount_str:
        return False
    digits = re.sub(r'[^\d]', '', amount_str)
    val = int(digits) if digits else 0
    
    # Genuine round numbers (multiples of 5 or 10) are normal
    if val > 0 and val % 5 == 0:
        return False
        
    # Check for off-by-one amounts (e.g. 499, 999, 1001)
    if val > 100:
        if (val + 1) % 100 == 0 or (val - 1) % 100 == 0:
            return True
            
    return False


def has_funny_utr_pattern(utr: str) -> bool:
    """
    Detects fake or mocked UTR numbers generated by spoof apps.
    Flags repeated characters (e.g. '11111', '00000') or obvious sequences ('123456').
    """
    if not utr:
        return False
    
    # Check for repeated identical characters of length 5 or more (e.g. 11111)
    if re.search(r'(.)\1{4,}', utr):
        return True
        
    # Check for common sequential runs
    sequences = ['123456', '012345', 'qwerty', 'abcdef']
    utr_lower = utr.lower()
    for seq in sequences:
        if seq in utr_lower:
            return True
            
    return False
